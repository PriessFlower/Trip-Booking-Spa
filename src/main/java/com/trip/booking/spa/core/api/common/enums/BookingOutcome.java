package com.trip.booking.spa.core.api.common.enums;

/**
 * 下单结果三态。
 *
 * <p><b>为什么必须有第三态</b>：本服务是供应商网关，订单归上游所有。调用供应商下单接口时，
 * 存在一类无法归入成功或失败的结果——请求已发出，但响应超时、连接中断，或返回 5xx/499
 * 这类既可能在供应商侧生效、也可能未生效的状态码。
 *
 * <p>此时若回报 {@link #FAILED}，上游会据此退款并释放库存，而供应商侧可能已真实成单，
 * 造成「已退款却仍占房」的两头空；若回报 {@link #SUCCESS}，则可能凭空承认一笔不存在的订单。
 * 二者都是资损。唯一正确的做法是如实回报 {@link #UNKNOWN}，由上游据此走查单确证与补提交。
 *
 * <p><b>判定纪律</b>：只有确证不会因重试而改变的结果（满房、售罄、参数非法、额度不足等）
 * 才可判 {@link #FAILED}；一切无法证明「请求未在供应商侧生效」的情形，一律判
 * {@link #UNKNOWN}。误判 UNKNOWN 的代价是上游多做一次查单（廉价），误判 FAILED 的代价
 * 是资损（昂贵）——判据向 UNKNOWN 倾斜是有意为之。
 */
public enum BookingOutcome {

    /** 供应商已确认成单，供应商订单号必然有值 */
    SUCCESS,

    /**
     * 确定失败，重试必再失败。仅用于供应商明确给出业务性拒绝的场景
     * （满房、售罄、参数非法、额度不足等）。上游可据此直接终结订单并退款。
     */
    FAILED,

    /**
     * 结果不确定：请求可能已在供应商侧生效。
     * 上游<b>禁止</b>据此退款或终结订单，必须先查单确证。
     */
    UNKNOWN
}
