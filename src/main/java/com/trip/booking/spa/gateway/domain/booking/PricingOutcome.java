package com.trip.booking.spa.gateway.domain.booking;

/**
 * 查价结果分态。
 *
 * <p><b>为什么查价也需要分态</b>：与 {@link CheckPriceOutcome} 是同一条纪律的另一面——
 * 「查不出价」至少有两种成因，而它们的正确处置互相矛盾：
 *
 * <ul>
 *   <li>{@link #NO_INVENTORY}——供应商明确回答该店该住期没有可售产品。上游应如实告知，
 *       不必重试，也不该拿任何陈价顶上</li>
 *   <li>{@link #INDETERMINATE}——我们没能问出结果（超时、被限流、5xx、响应无法判读）。
 *       房很可能还在，上游应稍后重试，<b>禁止</b>据此认定该店无房</li>
 * </ul>
 *
 * <p><b>塌成一态的代价</b>：本服务在 2026-08-20 之前，查价出口对这两者一律回
 * {@code code=-1, errorMsg="result is null"}——供应商明确无房、限流被拒、跨云超时、
 * 解析失败，上游收到的是同一句话。分辨力其实在适配层就有（艺龙 {@code isEmptyResult}
 * 返回空列表、调用失败返回 null），是在出口被丢掉的。
 *
 * <p>这正是 {@code docs/gateway-boundary.md} B7 列为网关职责的那一条：空响应三态可辨。
 * 上游 tg-trip-cursor 的取价函数把「死店」「真无房」「瞬时超时」一律返回空，
 * 结果是道旅韩国 41,934 个店级映射里 25.6% 是死 id、339 个死 id 残留 66,469 行
 * 在售僵尸价——同一个根因，方向相反：那边错在多卖，我们错在少卖。
 *
 * <p><b>纪律</b>：判定 {@link #NO_INVENTORY} 的权力只交给适配层（③），因为只有它读得懂
 * 供应商在说什么；契约层（②）与端点层（①）的一切兜底一律落到 {@link #INDETERMINATE}。
 */
public enum PricingOutcome {

    /** 查到了可售产品。此时产品列表必然非空 */
    AVAILABLE,

    /**
     * 供应商明确回答该店该住期无可售产品。确定性结果，重试不会改变。
     *
     * <p>业务闸口主动拒绝报价（如当天入住黑名单）也归入本态：对上游而言同样是
     * 「这里没有可卖的」且重试无用，报 {@link #INDETERMINATE} 只会诱发无谓重试。
     */
    NO_INVENTORY,

    /**
     * 未能得出结论：调用超时、被限流、供应商返回 5xx、响应无法判读，或凭据未配置。
     *
     * <p>上游<b>禁止</b>据此认定该店无房。刷价缓存未命中也属本态——
     * 「缓存里没有」只说明我们没刷到，不说明供应商没有。
     */
    INDETERMINATE
}
