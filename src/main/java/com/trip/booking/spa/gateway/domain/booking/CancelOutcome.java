package com.trip.booking.spa.gateway.domain.booking;

/**
 * 取消结果三态。
 *
 * <p><b>为什么取消也必须有第三态</b>：与下单同理，取消请求同样可能「已发出但响应丢失」——
 * 超时、连接中断、5xx。此时供应商侧可能已取消、也可能未取消。
 *
 * <p>取消的误判后果与下单方向相反，但同样是资损：判 {@link #FAILED} 而实际已取消，上游
 * 会继续持有一个其实已经不存在的订单，旅客到店无房；判 {@link #SUCCESS} 而实际未取消，
 * 上游据此退款放行，而房仍占着、费用仍在产生。
 *
 * <p><b>判定纪律</b>：只有确证不会因重试而改变的结果（订单不存在、已过取消期限、
 * 供应商明确拒绝）才可判 {@link #FAILED}；一切无法证明「取消请求未在供应商侧生效」的
 * 情形，一律判 {@link #UNKNOWN}，由上游查单确证。
 *
 * <p>误判 UNKNOWN 的代价是上游多查一次单（廉价），误判 SUCCESS 或 FAILED 的代价是
 * 房与钱对不上（昂贵）——判据向 UNKNOWN 倾斜是有意为之。
 *
 * @see BookingOutcome 下单侧的同构三态，判定纪律一致
 */
public enum CancelOutcome {

    /** 供应商已确认取消，该订单的全部房间均处于已取消状态 */
    SUCCESS,

    /**
     * 确定失败，重试必再失败。仅用于供应商明确给出业务性拒绝的场景
     * （订单不存在、已过免费取消期限、订单状态不允许取消等）。
     */
    FAILED,

    /**
     * 结果不确定：取消请求可能已在供应商侧生效。
     * 上游<b>禁止</b>据此判定订单仍然有效，必须先查单确证。
     */
    UNKNOWN
}
